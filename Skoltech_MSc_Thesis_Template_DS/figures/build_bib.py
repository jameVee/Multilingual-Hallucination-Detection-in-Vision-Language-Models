"""Assemble Bibliography.bib: template's PyTorch entry + paper/references.bib + figures/extra_refs.bib.

Usage (from the thesis folder):  python figures/build_bib.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
paper = (HERE.parent / "paper" / "references.bib").read_text(encoding="utf-8")
paper = re.sub(r'\n\s*abstract\s*=\s*".*?",?\n', "\n", paper, flags=re.S)
# the overview paper is now in the ACL Anthology: its published entry lives in extra_refs.bib
paper = re.sub(r"@misc\{vazquez2026shroomvisionsoverview,.*?\}\s*,\s*\}", "", paper, flags=re.S)
extra = (HERE / "figures" / "extra_refs.bib").read_text(encoding="utf-8")
paszke = """@article{paszke2019pytorch,
  title={Pytorch: An imperative style, high-performance deep learning library},
  author={Paszke, Adam and Gross, Sam and Massa, Francisco and Lerer, Adam and Bradbury, James and Chanan, Gregory and Killeen, Trevor and Lin, Zeming and Gimelshein, Natalia and Antiga, Luca and others},
  journal={Advances in neural information processing systems},
  volume={32},
  year={2019}
}"""
out = "% Generated by figures/build_bib.py\n\n" + paszke + "\n\n" + paper.strip() + "\n\n" + extra
(HERE / "Bibliography.bib").write_text(out, encoding="utf-8")

keys = set(re.findall(r"@\w+\{([^,\s]+),", out))
used = set()
for f in (HERE / "chapters").glob("*.tex"):
    for m in re.findall(r"\\cite\{([^}]*)\}", f.read_text(encoding="utf-8")):
        used.update(k.strip() for k in m.split(","))
print("missing:", sorted(used - keys))
print("unused:", sorted(keys - used))
